// Builds src/components/home/toolIcons.ts for the ToolsMarquee: only the
// marks we show, as {name, path, hex}, so simple-icons (CC0) never ships to
// the browser. Brands missing from simple-icons (removed for trademark
// reasons, or never added) get icon: null and render as a text wordmark.
//   node scripts/build-tool-icons.mjs
import fs from "node:fs";
import path from "node:path";
import * as si from "simple-icons";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "src/components/home/toolIcons.ts");

// Display name, then the simple-icons slug to try (null = wordmark only).
// Scorecard R2 fix 10 (21 Oct 2026): owners do not buy on developer tools, so
// OpenAI, Claude, Vercel, Supabase and Twilio are out; business apps are in.
const TOOLS = [
  ["WhatsApp", "whatsapp"],
  ["Gmail", "gmail"],
  ["Google Workspace", "google"],
  ["Google Calendar", "googlecalendar"],
  ["Microsoft 365", "microsoft365"],
  ["Outlook", "microsoftoutlook"],
  ["Shopify", "shopify"],
  ["WooCommerce", "woocommerce"],
  ["Wix", "wix"],
  ["WordPress", "wordpress"],
  ["Instagram", "instagram"],
  ["Facebook", "facebook"],
  ["Google Ads", "googleads"],
  ["HubSpot", "hubspot"],
  // Daniel's call (Oct 2026): the CRM may be named in this logo strip only;
  // everywhere else on the site it stays "your CRM".
  ["GoHighLevel", null],
  ["Calendly", "calendly"],
  ["Stripe", "stripe"],
  ["PayFast", "payfast"],
  ["Yoco", "yoco"],
  ["Xero", "xero"],
  ["Sage", "sage"],
  ["QuickBooks", "quickbooks"],
  ["Slack", "slack"],
  // Not in simple-icons (removed for trademark reasons): text wordmark.
  ["Microsoft Teams", null],
  ["Mailchimp", "mailchimp"],
  ["Zoho", "zoho"],
  ["Notion", "notion"],
  ["Airtable", "airtable"],
  ["Zapier", "zapier"],
  ["Make", "make"],
];

const bySlug = new Map(
  Object.values(si)
    .filter((o) => o && typeof o === "object" && "slug" in o)
    .map((o) => [o.slug, o]),
);

const rows = TOOLS.map(([name, slug]) => {
  const icon = slug ? bySlug.get(slug) : undefined;
  return icon ? { name, path: icon.path, hex: icon.hex } : { name, path: null, hex: null };
});

const missing = rows.filter((r) => !r.path).map((r) => r.name);
const body = `// Generated by scripts/build-tool-icons.mjs from simple-icons (CC0). Do not edit by hand.
export type ToolIcon = { name: string; path: string | null; hex: string | null };

export const TOOL_ICONS: ToolIcon[] = ${JSON.stringify(rows, null, 2)};
`;
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(root, out)}: ${rows.length - missing.length} icons, ${missing.length} wordmarks (${missing.join(", ")})`);
